/**
 * 로케일별 표. **지금은 국문뿐이다.**
 *
 * 다국어 화면은 같은 자리에 한글 원명을 쓴다 — 외국인 여행자가 택시 기사에게 보여주거나
 * 표지판과 대조해야 하므로 그쪽이 우선이다(GOAL.md §5-2). 그래서 다른 로케일의 표를
 * 수집하지 않았다. 필요해지면 해당 서비스의 코드 API 를 같은 방식으로 훑어 여기 더한다.
 */
const TABLES: Partial<Record<Locale, { cat3: Record<string, string>; lcls3: Record<string, string> }>> = {
  ko: { cat3: CAT3_KO, lcls3: LCLS3_KO },
};

/**
 * 이 장소가 무엇인지 한 마디로. 어느 표에도 없으면 `null`.
 *
 * 모르는 코드에 코드값을 그대로 보여주지 않는다 — 카드에 `A05020100` 이 뜨는 것은
 * 빈 줄보다 나쁘다.
 */
export function spotKindOf(
  cat3: string | null | undefined,
  lclsSystm3: string | null | undefined,
  locale: Locale,
): string | null {
  const t = TABLES[locale];
  if (!t) return null;
  const c = cat3?.trim();
  if (c && t.cat3[c]) return t.cat3[c];
  const l = lclsSystm3?.trim();
  if (l && t.lcls3[l]) return t.lcls3[l];
  return null;
}
